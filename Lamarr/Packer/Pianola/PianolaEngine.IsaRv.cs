    //指令字解码 内部字节码为小端 产物密文统一按大端存放 所以先读32位再换序后解码
    static void EmitIsaDecodeRv(StringBuilder sb)
    {
        sb.AppendLine("; ISA carrier decode, valid RV64 words to internal bytecode");
        sb.AppendLine("dec_entry:");
        sb.AppendLine("    mov rsi, rcx ; carrier stream read pointer");
        sb.AppendLine("    lea r14, [rdi+1000h] ; internal bytecode write pointer: VM code window");
        sb.AppendLine("dec_loop:");
        sb.AppendLine("    lea rax, [r14+16]");
        sb.AppendLine("    sub rax, rdi");
        sb.AppendLine("    cmp rax, 1FF0h");
        sb.AppendLine("    ja h_bad");
        sb.AppendLine("    mov eax, dword ptr [rsi]");
        sb.AppendLine("    bswap eax ; ciphertext is stored big endian, convert to host order");
        
        sb.AppendLine("    call a_rest ; ChaCha12 at-rest keystream word to edx");
        sb.AppendLine("    xor eax, edx ; at-rest decrypt");
        sb.AppendLine("    xor r15d, eax ; fold the decoded word into the chain state");
        sb.AppendLine("    add rsi, 4");
        sb.AppendLine("    cmp eax, 00008067h");//ret
        sb.AppendLine("    je d_blr");
        sb.AppendLine("    cmp eax, 000080E7h");//jalr x1,0
        sb.AppendLine("    je d_bctr");
        sb.AppendLine("    mov r11d, eax");
        sb.AppendLine("    and r11d, 7Fh ; opcode");
        sb.AppendLine("    cmp r11d, 37h");
        sb.AppendLine("    je d_lis");
        sb.AppendLine("    cmp r11d, 17h");
        sb.AppendLine("    je d_auipc");
        sb.AppendLine("    cmp r11d, 13h");
        sb.AppendLine("    je d_itype");
        sb.AppendLine("    cmp r11d, 33h");
        sb.AppendLine("    je d_xform");
        sb.AppendLine("    cmp r11d, 03h");
        sb.AppendLine("    je d_ld");
        sb.AppendLine("    cmp r11d, 23h");
        sb.AppendLine("    je d_st");
        sb.AppendLine("    jmp h_bad");
        //结束与返回兼作解码终止判定 随置换换位
        sb.AppendLine("d_blr:");
        sb.AppendLine("    mov byte ptr [r14], 0");
        sb.AppendLine("    inc r14");
        sb.AppendLine(OpTable.Map(OP_END) == OP_END ? "    jmp dec_done" : "    jmp dec_loop");
        sb.AppendLine("d_bctr:");
        sb.AppendLine("    mov byte ptr [r14], 1");
        sb.AppendLine("    inc r14");
        sb.AppendLine(OpTable.Map(OP_RET) == OP_RET ? "    jmp dec_loop" : "    jmp dec_done");
        //立即数搬移用高位装入+加立即数两条 目标寄存器在高位装入的目标字段 宽度码在加立即数的源字段 立即数高低位拼接
        sb.AppendLine("d_lis:");
        sb.AppendLine("    mov r11d, dword ptr [rsi]");
        sb.AppendLine("    bswap r11d");
        
        sb.AppendLine("    call a_rest ; ChaCha12 at-rest keystream word to edx");
        sb.AppendLine("    xor r11d, edx");
        sb.AppendLine("    xor r15d, r11d ; fold the decoded word into the chain state");
        sb.AppendLine("    add rsi, 4");
        sb.AppendLine("    mov r10d, r11d");
        sb.AppendLine("    and r10d, 7Fh");
        sb.AppendLine("    cmp r10d, 13h ; must be addi");
        sb.AppendLine("    jne h_bad");
        sb.AppendLine("    mov r10d, r11d");
        sb.AppendLine("    shr r10d, 12");
        sb.AppendLine("    and r10d, 7h");
        sb.AppendLine("    test r10d, r10d ; addi func3=0");
        sb.AppendLine("    jnz h_bad");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 7");
        sb.AppendLine("    and ecx, 31 ; rd");
        sb.AppendLine("    cmp ecx, 15");
        sb.AppendLine("    ja h_bad");
        sb.AppendLine("    mov r8d, r11d");
        sb.AppendLine("    shr r8d, 15");
        sb.AppendLine("    and r8d, 31 ; the rs1 field carries width code + noise");
        sb.AppendLine("    shr r8d, 3");
        sb.AppendLine("    and r8d, 3");
        sb.AppendLine("    lea r10, [d_wcode]");
        sb.AppendLine("    movzx r8d, byte ptr [r10+r8] ; width code to internal width");
        sb.AppendLine("    cmp r8d, 2");
        sb.AppendLine("    ja h_bad");
        sb.AppendLine("    mov edx, eax");
        sb.AppendLine("    shr edx, 12");
        sb.AppendLine("    shl edx, 12 ; hi20<<12");
        sb.AppendLine("    mov r9d, r11d");
        sb.AppendLine("    shr r9d, 20");
        sb.AppendLine("    shl r9d, 20");
        sb.AppendLine("    sar r9d, 20 ; signext12(lo12)");
        sb.AppendLine("    add edx, r9d ; uV");
        sb.AppendLine("    jmp d_mi_emit");
        sb.AppendLine("d_mi_emit:");
        sb.AppendLine("    mov byte ptr [r14], 8");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov byte ptr [r14], r8b");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    test r8d, r8d");
        sb.AppendLine("    je d_mi1");
        sb.AppendLine("    cmp r8d, 1");
        sb.AppendLine("    je d_mi2");
        sb.AppendLine("    mov dword ptr [r14], edx");
        sb.AppendLine("    add r14, 4");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_mi2:");
        sb.AppendLine("    mov word ptr [r14], dx");
        sb.AppendLine("    add r14, 2");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_mi1:");
        sb.AppendLine("    mov byte ptr [r14], dl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp dec_loop");
        //相对地址指令 目标字段是标记 区分跳转与条件跳转与调用 立即数字段承载条件码与偏移
        sb.AppendLine("d_auipc:");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 7");
        sb.AppendLine("    and ecx, 31 ; tag");
        sb.AppendLine("    mov edx, eax");
        sb.AppendLine("    shr edx, 12");
        sb.AppendLine("    and edx, 0FFFFFh ; payload");
        sb.AppendLine("    test ecx, ecx");
        sb.AppendLine("    je d_payjmp");
        sb.AppendLine("    cmp ecx, 1");
        sb.AppendLine("    je d_payjcc");
        sb.AppendLine("    cmp ecx, 2");
        sb.AppendLine("    je d_paycall");
        sb.AppendLine("    jmp h_bad");
        sb.AppendLine("d_payjmp:");
        sb.AppendLine("    mov byte ptr [r14], 1Dh");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov word ptr [r14], dx");
        sb.AppendLine("    add r14, 2");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_paycall:");
        sb.AppendLine("    mov byte ptr [r14], 1Fh");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov word ptr [r14], dx");
        sb.AppendLine("    add r14, 2");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_payjcc:");
        sb.AppendLine("    mov byte ptr [r14], 1Eh");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov ecx, edx");
        sb.AppendLine("    shr ecx, 16 ; cond");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov word ptr [r14], dx");
        sb.AppendLine("    add r14, 2");
        sb.AppendLine("    jmp dec_loop");
    }

    static void EmitIsaDecodeRv2(StringBuilder sb)
    {
        sb.AppendLine("d_itype:");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 12");
        sb.AppendLine("    and r10d, 7h ; funct3");
        sb.AppendLine("    test r10d, r10d");
        sb.AppendLine("    je d_movreg");
        sb.AppendLine("    cmp r10d, 4");
        sb.AppendLine("    je d_not");
        sb.AppendLine("    jmp h_bad");
        sb.AppendLine("d_movreg:");
        sb.AppendLine("    mov byte ptr [r14], 9");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp d_pair");
        sb.AppendLine("d_not:");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 7");
        sb.AppendLine("    and ecx, 0Fh ; rd (the register field carries no width bit)");
        sb.AppendLine("    mov edx, eax");
        sb.AppendLine("    shr edx, 23 ; imm12[4:3] = width code (word bits 24:23)");
        sb.AppendLine("    and edx, 3");
        sb.AppendLine("    lea r11, [d_wcode]");
        sb.AppendLine("    movzx r8d, byte ptr [r11+rdx]");
        sb.AppendLine("    mov r9d, 0F0h");
        sb.AppendLine("    add r9d, r8d");
        sb.AppendLine("    mov byte ptr [r14], r9b");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_pair:");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 7");
        sb.AppendLine("    and ecx, 0Fh ; rd");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 15");
        sb.AppendLine("    and r10d, 0Fh ; rs1");
        sb.AppendLine("    shl r10d, 4");
        sb.AppendLine("    or ecx, r10d");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_ld:");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 12");
        sb.AppendLine("    and r10d, 3h");
        sb.AppendLine("    add r10d, 10h ; LD 0x10+w");
        sb.AppendLine("    mov byte ptr [r14], r10b");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp d_pair");
        sb.AppendLine("d_st:");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 12");
        sb.AppendLine("    and r10d, 3h");
        sb.AppendLine("    add r10d, 14h ; ST 0x14+w");
        sb.AppendLine("    mov byte ptr [r14], r10b");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 20");
        sb.AppendLine("    and ecx, 0Fh ; rs2 = data register");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 15");
        sb.AppendLine("    and r10d, 0Fh ; rs1 = address register");
        sb.AppendLine("    shl r10d, 4");
        sb.AppendLine("    or ecx, r10d");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_xform:");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 25");
        sb.AppendLine("    and r10d, 7Fh ; funct7");
        sb.AppendLine("    mov r9d, eax");
        sb.AppendLine("    shr r9d, 12");
        sb.AppendLine("    and r9d, 7h ; funct3");
        sb.AppendLine("    shl r10d, 3");
        sb.AppendLine("    or r10d, r9d ; key = (f7<<3)|f3");
        for (int k = 0; k < Fam.Length; k++)//族表只保留编码器那一份 (f7,f3) 与 Fam 同序
        {
            var fw = NotenrolleIsaRv.rgFamMap[k];
            sb.AppendLine($"    cmp r10d, 0{(fw.Item1 << 3) | fw.Item2:X}h");
            sb.AppendLine("    je d_fam_" + Fam[k].Item2);
        }
        sb.AppendLine("    cmp r10d, 1A5h ; rev8 form (f7=34h,f3=5) maps to BSWAP");
        sb.AppendLine("    je d_bswap");
        sb.AppendLine("    cmp r10d, 2");
        sb.AppendLine("    jne h_bad");
        sb.AppendLine("    mov byte ptr [r14], 1Ch ; CMP(f7=0,f3=2 means slt)");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp d_pair");
        foreach (var f in Fam)
        {
            sb.AppendLine($"d_fam_{f.Item2}:");
            sb.AppendLine($"    mov r9d, 0{f.Item1:X}h");
            sb.AppendLine("    jmp d_alu");
        }
        sb.AppendLine("d_alu:");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 7");
        sb.AppendLine("    and ecx, 0Fh ; rd (the register field carries no width bit)");
        sb.AppendLine("    mov edx, eax");
        sb.AppendLine("    shr edx, 23 ; rs2[4:3] = width code (word bits 24:23)");
        sb.AppendLine("    and edx, 3");
        sb.AppendLine("    lea r11, [d_wcode]");
        sb.AppendLine("    movzx r8d, byte ptr [r11+rdx]");
        sb.AppendLine("    add r9d, r8d ; internal op = family base + width");
        sb.AppendLine("    mov byte ptr [r14], r9b");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov r10d, eax");
        sb.AppendLine("    shr r10d, 7");
        sb.AppendLine("    and r10d, 0Fh ; rd");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 15");
        sb.AppendLine("    and ecx, 0Fh ; rs1");
        sb.AppendLine("    shl ecx, 4");
        sb.AppendLine("    or ecx, r10d");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp dec_loop");
        sb.AppendLine("d_bswap:");
        sb.AppendLine("    mov ecx, eax");
        sb.AppendLine("    shr ecx, 7");
        sb.AppendLine("    and ecx, 0Fh ; rd");
        sb.AppendLine("    mov edx, eax");
        sb.AppendLine("    shr edx, 23 ; rs2[4:3] = width code (word bits 24:23)");
        sb.AppendLine("    and edx, 3");
        sb.AppendLine("    lea r11, [d_wcode]");
        sb.AppendLine("    movzx r8d, byte ptr [r11+rdx]");
        sb.AppendLine("    mov r9d, 18h ; BSWAP family base");
        sb.AppendLine("    add r9d, r8d");
        sb.AppendLine("    mov byte ptr [r14], r9b");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    mov byte ptr [r14], cl");
        sb.AppendLine("    inc r14");
        sb.AppendLine("    jmp dec_loop");
    }

